(function() {
	'use strict';

	var form = document.getElementById('ai-advisor-form');
	var question = document.getElementById('advisor-question');
	var status = document.getElementById('ai-advisor-status');
	var response = document.getElementById('ai-advisor-response');

	if (!form || !question || !status || !response)
		return;

	var submitButton = form.querySelector('button[type="submit"]');

	function setStatus(message) {
		status.textContent = message || '';
	}

	function setResponse(message, isError) {
		response.textContent = message;
		response.classList.toggle('is-error', !!isError);
	}

	form.addEventListener('submit', function(event) {
		event.preventDefault();

		var prompt = question.value.trim();

		if (prompt.length < 8) {
			setResponse('Please ask a more specific question about Sai Kiran\'s skills, projects, or fit for a role.', true);
			question.focus();
			return;
		}

		submitButton.disabled = true;
		setStatus('Thinking through the portfolio context...');
		setResponse('Generating a grounded answer from the server-side AI endpoint.', false);

		fetch('/api/portfolio-advisor', {
			method: 'POST',
			headers: {
				'Content-Type': 'application/json',
				'Accept': 'application/json'
			},
			body: JSON.stringify({ question: prompt })
		})
			.then(function(result) {
				return result.json().catch(function() {
					throw new Error('The server returned an unreadable response.');
				}).then(function(payload) {
					if (!result.ok || !payload.ok)
						throw new Error(payload.error || 'The AI advisor is temporarily unavailable.');

					return payload;
				});
			})
			.then(function(payload) {
				setStatus('Answer generated by the AI Portfolio Advisor.');
				setResponse(payload.answer, false);
			})
			.catch(function(error) {
				setStatus('Unable to complete the AI request.');
				setResponse(error.message || 'The AI advisor is temporarily unavailable. Please try again shortly.', true);
			})
			.finally(function() {
				submitButton.disabled = false;
			});
	});
})();
